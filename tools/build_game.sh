#!/bin/bash
# Builds the game headlessly, the same way the Defold editor's own Build
# commands do, so that a `ddev restart` in the sibling website project
# (laravel/) refreshes what that site serves. Wired in as a post-start hook by
# laravel/.ddev/config.galaxy-proxy.yaml (which means it runs on `ddev start`
# and `ddev restart` alike); also fine to run by hand.
#
# Two things get built, because the DDEV setup uses both:
#
#   HTML5 (wasm-web) -> build/default_html5/__htmlLaunchDir, the exact folder
#     laravel's nginx serves as play.ddev.site (see that project's
#     .ddev/docker-compose.game-proxy.yaml). Rebuilding it here is what keeps
#     the browser from serving a stale bundle after a data/script change - the
#     trap recorded in plan.md ("ddev restart does not rebuild this - the
#     bundle is only regenerated by building HTML5 in the Defold editor").
#   Desktop (macOS) -> build/arm64-osx/dmengine, what tools/run_windowed.sh
#     launches.
#
# Both are debug builds on purpose: the README's local play paths
# (`index.html#dev_token=...`, `GALAXY_PLAY_TOKEN`) only work in a debug build,
# which is also the build every live test in plan.md was run against.
#
# Bob comes from the installed Defold editor (so this always builds with the
# same Defold version you develop in) rather than a downloaded bob.jar. These
# invocation details are load-bearing, and all of them were learned the hard way
# (plan.md §3.6):
#
#   * the bundled JAR is NOT runnable with `java -jar`: its manifest Main-Class
#     is com.defold.editor.Main - the editor GUI - which starts headless and
#     hangs with no output at all. The explicit com.dynamo.bob.Bob main class is
#     required.
#   * `--output` has to be relative to the project root; an absolute path is a
#     hard error ("Build directory must be relative to root directory").
#
# No `--platform` for the desktop build: bob then builds the host's own
# platform, which is what puts the engine in build/arm64-osx - the path
# tools/run_windowed.sh looks at. Naming it explicitly (`--platform
# arm64-macos`) moves the engine to build/arm64-macos instead. On an Intel Mac
# the same omission puts it in build/x86_64-osx, which that script won't find.
#
# Both builds are incremental - bob caches in the build directory - so an
# unchanged project costs a few seconds per platform (~14s for both here). A
# cold build (no build/ directory, or the first build after
# a dependency change) recompiles the websocket native extension on Defold's
# build server and takes minutes, so it needs working outbound internet.
#
# Exits non-zero if either build fails. DDEV does not abort a restart on hook
# failure, so a broken game never stops the website coming up - but the failure
# is printed loudly, because quietly serving a stale bundle is exactly the
# problem this script exists to remove.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOG="$REPO_DIR/build/build_game.log"

# The jar carries the editor's Defold SDK hash in its name and the JDK lives in
# a versioned folder, so glob both instead of hardcoding versions that a Defold
# update would invalidate. DEFOLD_APP can point at a second install.
DEFOLD_APP="${DEFOLD_APP:-/Applications/Defold.app}"
PACKAGES="$DEFOLD_APP/Contents/Resources/packages"
JAR="$(ls -t "$PACKAGES"/defold-*.jar 2>/dev/null | head -n 1 || true)"
JAVA="$(ls -td "$PACKAGES"/jdk-*/bin/java 2>/dev/null | head -n 1 || true)"

# A machine without the editor still gets a website: skip rather than fail.
if [ -z "$JAR" ] || [ -z "$JAVA" ] || [ ! -x "$JAVA" ]; then
	echo "build_game.sh: no Defold editor under $DEFOLD_APP - skipping the game build." >&2
	echo "  Set DEFOLD_APP if the editor lives somewhere else." >&2
	exit 0
fi

mkdir -p "$REPO_DIR/build"
: > "$LOG"

failed=0

# run_bob <label> <bob args...>, where the args end in the bob targets to run.
run_bob() {
	local label="$1"
	shift
	printf '\n### %s\n' "$label" >> "$LOG"
	# -Dcom.google.protobuf.use_unsafe_pre22_gencode: bob's bundled protobuf
	# gencode predates 21.7 and warns about it on every single run; bob's own
	# message names this property as the supported way to silence that warning.
	# It silences only that warning, and does not affect what gets built.
	if (cd "$REPO_DIR" && "$JAVA" -Dcom.google.protobuf.use_unsafe_pre22_gencode \
			-cp "$JAR" com.dynamo.bob.Bob --root "$REPO_DIR" "$@") >> "$LOG" 2>&1; then
		echo "  ok      $label"
	else
		echo "  FAILED  $label" >&2
		failed=1
	fi
}

# The HTML5 build has to write into build/default_html5 (its own data
# directory, so it doesn't disturb the desktop build's) and bundle into the
# __htmlLaunchDir subfolder nginx serves.
run_bob "HTML5 build (served as play.ddev.site)" \
	--platform wasm-web --architectures wasm-web --variant debug --archive \
	--output build/default_html5 \
	--bundle-output build/default_html5/__htmlLaunchDir \
	resolve build bundle

# --archive: without it bob refreshes the loose built resources but leaves the
# previous game.arcd/game.dmanifest in place, i.e. a half-updated data
# directory a stale set of resources - the exact failure mode this hook exists
# to prevent.
run_bob "desktop build (tools/run_windowed.sh)" \
	--variant debug --archive \
	resolve build

# bob writes dmengine without the executable bit, so a build that has not been
# chmod'ed can't be launched by tools/run_windowed.sh.
ENGINE="$REPO_DIR/build/arm64-osx/dmengine"
if [ -f "$ENGINE" ] && [ ! -x "$ENGINE" ]; then
	chmod +x "$ENGINE"
fi

if [ "$failed" -ne 0 ]; then
	echo "build_game.sh: a build failed - the site keeps serving the previous bundle." >&2
	# bob writes one clean "ERROR: <file>:<line>: ..." line per failure before also
	# logging the Java stack traces, so report those lines rather than a blind
	# tail of the log (which is mostly stack trace). De-duplicated because a
	# single bad file fails both builds and so is reported twice.
	if grep -q '^ERROR' "$LOG"; then
		grep '^ERROR' "$LOG" | awk '!seen[$0]++' | tail -n 5 | sed 's/^/  /' >&2
	else
		tail -n 20 "$LOG" | sed 's/^/  /' >&2
	fi
	echo "  full log: $LOG" >&2
	exit 1
fi

echo "Game builds up to date (log: $LOG)."
